"""Общие классы ошибок обработки одного Kafka-сообщения — используются и
рендер-, и send-стадией, чтобы consumer.py мог единообразно решать
"ретраить" или "не ретраить", не зная деталей конкретной бизнес-ошибки."""


class TransientProcessingError(Exception):
    """Повторяемая ошибка: внешняя зависимость (auth_service/SMTP/Postgres)
    временно недоступна. Consumer.py ретраит сообщение с backoff, а после
    исчерпания попыток — приостанавливает партицию и повторяет позже, не
    коммитя offset (at-least-once, уведомление не теряется)."""


class PermanentProcessingError(Exception):
    """Неповторяемая ошибка: сообщение само по себе не может быть
    обработано ни при каком числе попыток (битый JSON, пользователь не
    найден, шаблон не найден, невалидный email). Обработчик должен
    ЗАРАНЕЕ записать причину в notification_worker_dlq/notification_log
    перед тем, как поднять это исключение — consumer.py в ответ на него
    только коммитит offset и переходит к следующему сообщению."""
